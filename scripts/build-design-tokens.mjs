import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tokenPath = path.join(rootDir, "design.tokens.json");
const cssOutputPath = path.join(rootDir, "packages/tokens/css/tokens.generated.css");
const metadataOutputPath = path.join(rootDir, "packages/tokens/metadata/tokens.generated.mjs");
const metadataTypesOutputPath = path.join(rootDir, "packages/tokens/metadata/tokens.generated.d.ts");
const checkMode = process.argv.includes("--check");

const colorNames = [
  "background",
  "card",
  "foreground",
  "muted-foreground",
  "subtle-foreground",
  "border",
  "border-strong",
  "primary",
  "primary-soft",
  "grid",
];

function readTokens() {
  return JSON.parse(fs.readFileSync(tokenPath, "utf8"));
}

function getNode(tokens, pathValue) {
  return pathValue.split(".").reduce((node, part) => {
    if (!node || typeof node !== "object" || !(part in node)) {
      throw new Error(`Unresolvable token reference: ${pathValue}`);
    }
    return node[part];
  }, tokens);
}

function inheritedType(tokens, pathValue) {
  const parts = pathValue.split(".");
  let node = tokens;
  let type;

  for (const part of parts) {
    if (!node || typeof node !== "object" || !(part in node)) {
      throw new Error(`Unresolvable token path: ${pathValue}`);
    }
    node = node[part];
    if (node && typeof node === "object" && typeof node.$type === "string") {
      type = node.$type;
    }
  }

  if (node && typeof node === "object" && typeof node.$type === "string") {
    type = node.$type;
  }

  if (!type) {
    throw new Error(`Token path has no inherited $type: ${pathValue}`);
  }

  return type;
}

function resolveToken(tokens, pathValue, expectedType, seen = new Set()) {
  if (seen.has(pathValue)) {
    throw new Error(`Circular token reference: ${[...seen, pathValue].join(" -> ")}`);
  }

  const node = getNode(tokens, pathValue);
  const actualType = inheritedType(tokens, pathValue);

  if (actualType !== expectedType) {
    throw new Error(`Token ${pathValue} is ${actualType}, expected ${expectedType}`);
  }

  if (!node || typeof node !== "object" || !("$value" in node)) {
    throw new Error(`Reference does not point to a token leaf: ${pathValue}`);
  }

  if (typeof node.$value === "string") {
    const match = node.$value.match(/^\{(.+)\}$/);
    if (!match) {
      throw new Error(`Invalid alias syntax at ${pathValue}: ${node.$value}`);
    }
    seen.add(pathValue);
    return resolveToken(tokens, match[1], expectedType, seen);
  }

  return node.$value;
}

function formatNumber(value) {
  if (!Number.isFinite(value)) {
    throw new Error(`Expected finite number, received ${value}`);
  }
  return Number(value.toFixed(4)).toString();
}

function serializeColor(value) {
  if (!value || typeof value !== "object" || value.colorSpace !== "oklch") {
    throw new Error("Only structured OKLCH color tokens are supported");
  }

  const { components, alpha } = value;
  if (!Array.isArray(components) || components.length !== 3) {
    throw new Error("OKLCH color tokens must have exactly three components");
  }

  const body = components.map(formatNumber).join(" ");
  if (alpha === undefined || alpha === 1) {
    return `oklch(${body})`;
  }
  return `oklch(${body} / ${formatNumber(alpha)})`;
}

function serializeDimension(value) {
  if (!value || typeof value !== "object") {
    throw new Error("Dimension token values must be objects");
  }

  if (!Number.isFinite(value.value) || typeof value.unit !== "string") {
    throw new Error("Dimension tokens must include numeric value and unit");
  }

  return `${formatNumber(value.value)}${value.unit}`;
}

function semanticColor(tokens, mode, name) {
  return serializeColor(resolveToken(tokens, `color.semantic.${mode}.${name}`, "color"));
}

function dimension(tokens, pathValue) {
  return serializeDimension(resolveToken(tokens, pathValue, "dimension"));
}

function linesForMode(tokens, mode, indent = "  ") {
  return colorNames.map(
    (name) => `${indent}--${name}: ${semanticColor(tokens, mode, name)}; /* ${mode} semantic color */`,
  );
}

function buildCss(tokens) {
  const railWidth = dimension(tokens, "dimension.layout.rail.width");
  const railGap = dimension(tokens, "dimension.layout.rail.gap");
  const lightLines = linesForMode(tokens, "light");
  const darkLines = linesForMode(tokens, "dark", "    ");

  return [
    "/* GENERATED by scripts/build-design-tokens.mjs - do not edit; run `pnpm design:build`. */",
    "",
    ":root {",
    "  /* @tokens Colors",
    "     @presenter Color */",
    ...lightLines,
    "  /* @tokens-end */",
    "",
    "  /* @tokens Layout",
    "     @presenter Spacing */",
    `  --rail-width: ${railWidth};`,
    `  --rail-gap: ${railGap};`,
    "  --rail-offset: calc(var(--rail-width) + var(--rail-gap));",
    "  /* @tokens-end */",
    "}",
    "",
    "@media (prefers-color-scheme: dark) {",
    "  :root {",
    "    /* @tokens Colors",
    "       @presenter Color */",
    ...darkLines,
    "    /* @tokens-end */",
    "  }",
    "}",
    "",
  ].join("\n");
}

function tokenLeaf(tokens, pathValue) {
  const node = getNode(tokens, pathValue);
  if (!node || typeof node !== "object" || !("$value" in node)) {
    throw new Error(`Expected token leaf at ${pathValue}`);
  }
  return node;
}

function metadataColor(tokens, mode, name) {
  const pathValue = `color.semantic.${mode}.${name}`;
  const node = tokenLeaf(tokens, pathValue);
  return {
    name,
    cssVariable: `--${name}`,
    type: "color",
    category: "Colors",
    mode,
    value: node.$value,
    resolvedValue: semanticColor(tokens, mode, name),
    sourcePath: pathValue,
  };
}

function metadataDimension(tokens, name, pathValue, cssVariable, resolvedValue = dimension(tokens, pathValue)) {
  const node = tokenLeaf(tokens, pathValue);
  return {
    name,
    cssVariable,
    type: "dimension",
    category: "Layout",
    value: node.$value,
    resolvedValue,
    sourcePath: pathValue,
  };
}

function buildMetadata(tokens) {
  const colorTokens = ["light", "dark"].flatMap((mode) =>
    colorNames.map((name) => metadataColor(tokens, mode, name)),
  );
  const railWidth = metadataDimension(tokens, "rail-width", "dimension.layout.rail.width", "--rail-width");
  const railGap = metadataDimension(tokens, "rail-gap", "dimension.layout.rail.gap", "--rail-gap");
  const railOffset = {
    name: "rail-offset",
    cssVariable: "--rail-offset",
    type: "dimension",
    category: "Layout",
    value: "calc({dimension.layout.rail.width} + {dimension.layout.rail.gap})",
    resolvedValue: "calc(var(--rail-width) + var(--rail-gap))",
    sourcePath: "dimension.layout.rail",
  };
  const layoutTokens = [railWidth, railGap, railOffset];

  return {
    generatedBy: "scripts/build-design-tokens.mjs",
    source: "design.tokens.json",
    exports: {
      css: "@mun.digital/tokens/css",
      metadata: "@mun.digital/tokens/metadata",
    },
    categories: [
      {
        name: "Colors",
        description: "Semantic color variables resolved from light and dark OKLCH token aliases.",
        tokens: colorTokens,
      },
      {
        name: "Layout",
        description: "Layout variables shared by the portfolio rail and extracted UI slice.",
        tokens: layoutTokens,
      },
    ],
    tokens: [...colorTokens, ...layoutTokens],
  };
}

function buildMetadataModule(tokens) {
  return [
    "/* GENERATED by scripts/build-design-tokens.mjs - do not edit; run `pnpm design:build`. */",
    "",
    `export const tokenMetadata = ${JSON.stringify(buildMetadata(tokens), null, 2)};`,
    "",
    "export default tokenMetadata;",
    "",
  ].join("\n");
}

function buildMetadataTypes() {
  return [
    "export interface MunDigitalTokenMetadataEntry {",
    "  name: string;",
    "  cssVariable: string;",
    "  type: \"color\" | \"dimension\";",
    "  category: \"Colors\" | \"Layout\";",
    "  mode?: \"light\" | \"dark\";",
    "  value: unknown;",
    "  resolvedValue: string;",
    "  sourcePath: string;",
    "}",
    "",
    "export interface MunDigitalTokenMetadataCategory {",
    "  name: \"Colors\" | \"Layout\";",
    "  description: string;",
    "  tokens: MunDigitalTokenMetadataEntry[];",
    "}",
    "",
    "export interface MunDigitalTokenMetadata {",
    "  generatedBy: string;",
    "  source: string;",
    "  exports: {",
    "    css: \"@mun.digital/tokens/css\";",
    "    metadata: \"@mun.digital/tokens/metadata\";",
    "  };",
    "  categories: MunDigitalTokenMetadataCategory[];",
    "  tokens: MunDigitalTokenMetadataEntry[];",
    "}",
    "",
    "export const tokenMetadata: MunDigitalTokenMetadata;",
    "export default tokenMetadata;",
    "",
  ].join("\n");
}

const tokens = readTokens();
const css = buildCss(tokens);
const metadata = buildMetadataModule(tokens);
const metadataTypes = buildMetadataTypes();

if (checkMode) {
  const currentCss = fs.existsSync(cssOutputPath) ? fs.readFileSync(cssOutputPath, "utf8") : "";
  const currentMetadata = fs.existsSync(metadataOutputPath) ? fs.readFileSync(metadataOutputPath, "utf8") : "";
  const currentMetadataTypes = fs.existsSync(metadataTypesOutputPath)
    ? fs.readFileSync(metadataTypesOutputPath, "utf8")
    : "";
  if (currentCss !== css || currentMetadata !== metadata || currentMetadataTypes !== metadataTypes) {
    console.error("Generated token outputs are stale. Run `pnpm design:build`.");
    process.exit(1);
  }
} else {
  fs.mkdirSync(path.dirname(cssOutputPath), { recursive: true });
  fs.mkdirSync(path.dirname(metadataOutputPath), { recursive: true });
  fs.writeFileSync(cssOutputPath, css);
  fs.writeFileSync(metadataOutputPath, metadata);
  fs.writeFileSync(metadataTypesOutputPath, metadataTypes);
  console.log("design tokens built");
}
